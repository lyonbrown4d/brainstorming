import type {
  Command,
  MindMapDocument,
  MindMapWorkbook,
  SearchMatch,
  SearchOptions,
  WorkbookCommand,
} from '@core'
import type { MindMapLayout } from '@layout'

export type EditorOperation =
  | { readonly kind: 'topic'; readonly sheetId: string; readonly command: Command }
  | { readonly kind: 'workbook'; readonly command: WorkbookCommand }
  | { readonly kind: 'undo' | 'redo' }
export interface NativeEditorSnapshot {
  readonly sessionId: string
  /** Decimal string avoids losing a Rust u64 through JavaScript numbers. */
  readonly revision: string
  readonly workbook: MindMapWorkbook
  readonly canUndo: boolean
  readonly canRedo: boolean
}
export interface NativeLayoutInput {
  readonly document: MindMapDocument
  readonly measurements: readonly {
    readonly id: string
    readonly width: number
    readonly height: number
  }[]
}
export interface NativeSpatialLayout {
  /** Physical native 2D geometry; the renderer applies only the view angle. */
  readonly layout: MindMapLayout
  readonly depths: Readonly<Record<string, number>>
}
export interface NativeSheetScene {
  readonly svg: string
  readonly width: number
  readonly height: number
}
/** Paths are generated by the shared renderer algorithms in layout coordinates. */
export interface VisualGeometry {
  readonly measurements: NativeLayoutInput['measurements']
  readonly topicOutlines: Readonly<Record<string, string>>
  readonly topicFills: Readonly<Record<string, string>>
  readonly topicAccents: Readonly<Record<string, string>>
  readonly edgePaths: Readonly<Record<string, string>>
  readonly decorationPaths: Readonly<Record<string, string>>
  readonly drawingPaths: Readonly<Record<string, string>>
  readonly markerIcons: Readonly<Record<string, readonly string[]>>
}
/** Business view models wrap the generated Tauri wire bindings; no stringly invoke calls here. */
export interface ComputeAPI {
  openSession(sessionId: string, workbook: MindMapWorkbook): Promise<NativeEditorSnapshot>
  executeSession(
    sessionId: string,
    revision: string,
    operation: EditorOperation,
  ): Promise<NativeEditorSnapshot>
  closeSession(sessionId: string): Promise<void>
  layout(input: NativeLayoutInput): Promise<MindMapLayout>
  spatialLayout(input: NativeLayoutInput): Promise<NativeSpatialLayout>
  find(
    input: { readonly workbookId: string; readonly query: string } & SearchOptions,
  ): Promise<SearchMatch[]>
  renderSheet(
    workbook: MindMapWorkbook,
    sheetId: string,
    includeCollapsed: boolean,
    geometry?: VisualGeometry,
  ): Promise<NativeSheetScene>
  refreshPreviews(input: {
    readonly documentId: string
    readonly contents: string
    readonly coverSheetId: string
    readonly geometry: Readonly<Record<string, VisualGeometry>>
  }): Promise<void>
  importText(format: 'md' | 'opml' | 'txt', text: string): Promise<MindMapWorkbook>
  exportFormat(
    workbook: MindMapWorkbook,
    format: 'xmind' | 'md' | 'opml' | 'txt',
    sheetId?: string,
  ): Promise<string | null>
}
