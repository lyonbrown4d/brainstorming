import { expect, test } from '@playwright/test'

test('keeps the active title and caret mounted when the canvas shrinks', async ({ page }) => {
  await page.setViewportSize({ width: 411, height: 914 })
  await page.goto('/iframe.html?id=brainstorming-画布自由绘图--mixed-selection&viewMode=story')
  const branch = page.locator('.react-flow__node[data-id="branch"]')
  await expect(branch).toBeVisible()
  await expect(page.locator('[data-canvas-loading]')).toHaveCount(0)
  await branch.click()
  await page.keyboard.press('F2')
  const editor = page.getByRole('textbox', { name: '编辑主题标题', exact: true })
  await expect(editor).toBeFocused()
  await page.keyboard.type('Draft ')
  await expect(editor).toHaveText('Draft ')
  const original = await editor.elementHandle()
  await page.setViewportSize({ width: 411, height: 360 })
  await expect(editor).toBeFocused()
  expect(await original.evaluate((element) => element.isConnected)).toBe(true)
  await page.keyboard.type('after resize')
  await page.keyboard.press('Enter')
  await expect(branch).toContainText('Draft after resize')
  await expect(editor).toHaveCount(0)
  await page.keyboard.press('ControlOrMeta+z')
  await expect(branch).toContainText('关联节点')
})
